from typing import Dict, Any

def infer_game_genre(detected_words: set) -> str:
    """Infers the Roblox game genre from detected OCR text."""
    corpus = " ".join([w.lower() for w in detected_words])
    
    if any(k in corpus for k in ["pet", "egg", "rebirth", "click", "multiplier", "hatch", "coins", "strength", "tap"]):
        return "Simulator (Clicker / Pet Hatching / Progression)"
    elif any(k in corpus for k in ["dropper", "collector", "conveyor", "tycoon", "factory", "deposit"]):
        return "Tycoon (Base Building & Automated Economy)"
    elif any(k in corpus for k in ["stage", "checkpoint", "timer", "obby", "jump", "speedrun"]):
        return "Obby (Obstacle Course)"
    elif any(k in corpus for k in ["quest", "inventory", "level", "xp", "sword", "stats", "dungeon", "mana"]):
        return "RPG / Adventure (Combat & Leveling)"
    elif any(k in corpus for k in ["monster", "door", "dark", "survive", "escape", "jumpscare"]):
        return "Horror (Survival & Escape)"
    elif any(k in corpus for k in ["storm", "loot", "elimination", "royale", "arena", "pvp"]):
        return "Battle Royale / PvP Arena"
    return "Custom Roblox Experience"

def build_super_prompt(game_title: str, target_dir: str, ocr_data: Dict[str, Any]) -> str:
    """Synthesizes the complete Master Clone / Inspiration Super Prompt."""
    all_words = set()
    for item in ocr_data.values():
        for t in item.get("texts", []):
            all_words.add(t)

    genre = infer_game_genre(all_words)

    lines = []
    lines.append(f"# MASTER CLONE IMPLEMENTATION SPECIFICATION (SUPER PROMPT)")
    lines.append(f"<!-- Generated by get-inspiration-roblox -->\n")
    lines.append(f"> **Reference Game Inspiration:** {game_title}")
    lines.append(f"> **Detected Genre:** {genre}")
    lines.append(f"> **Captured Reference Screens:** {len(ocr_data)}")
    lines.append(f"> **Screenshots Path:** `{target_dir}`\n")
    lines.append("Use this document as an exhaustive, production-grade specification to build an inspired or replica game in Roblox Studio.\n")

    lines.append("---")
    lines.append("## 1. Visual Reference Breakdown & Screens\n")

    for filename, info in sorted(ocr_data.items()):
        lines.append(f"### Screen: `{filename}`")
        color_badges = " ".join([f"`{c}`" for c in info.get("colors", [])])
        lines.append(f"- **Dominant Palette:** {color_badges}")
        
        texts = info.get("texts", [])
        if texts:
            lines.append("- **Detected Labels & Buttons:**")
            for t in texts[:12]:
                lines.append(f"  - \"{t}\"")
        else:
            lines.append("- *(Full-screen HUD / 3D Gameplay view)*")
        lines.append("")

    lines.append("---")
    lines.append("## 2. Reverse-Engineered Game Loop & Progression\n")
    lines.append(f"### Genre: {genre}")
    lines.append("### Core Gameplay Loop:")
    lines.append("1. **Spawn & First-Time Experience:** Player enters the hub, discovers primary interactables and persistent HUD.")
    lines.append("2. **Primary Activity:** Clicking/harvesting or performing core game actions to earn the base currency.")
    lines.append("3. **Economy Conversion:** Accumulating currency to spend on upgrades, multipliers, or unlocked areas.")
    lines.append("4. **Modal Progression:** Opening dedicated modals (Shop, Pets, Upgrades, Rebirths) to upgrade stats.")
    lines.append("5. **Prestige / Expansion Loop:** Reaching milestones triggers prestige (Rebirth) resetting base currency in exchange for global multipliers.\n")

    lines.append("---")
    lines.append("## 3. UI/UX Hierarchy Specification (`StarterGui`)\n")
    lines.append("### Design Language:")
    lines.append("- **Style:** Textured cartoon / clean modern Roblox UI with contrasting outlines and rounded corners (`UICorner` 8-12px).")
    lines.append("- **Layout Constraints:** Responsive scaling using Scale-based sizing and `UIAspectRatioConstraint` to ensure mobile & PC compatibility.")
    lines.append("- **Modal Transitions:** Popups open via `TweenService` (Scale from 0.8 to 1.0 with Back easing, 0.25s).\n")

    lines.append("### ScreenGui Architecture:")
    lines.append("```text")
    lines.append("StarterGui/")
    lines.append("├── HUD_ScreenGui/")
    lines.append("│   ├── TopCurrencyBar (Coins, Gems, Level)")
    lines.append("│   └── SidebarButtons (Shop, Upgrades, Rebirth, Settings)")
    lines.append("└── Modals_ScreenGui/")
    lines.append("    ├── ShopModal (ScrollingFrame with UIGridLayout cards)")
    lines.append("    ├── RebirthModal (Progress bar + Rebirth button)")
    lines.append("    └── SettingsModal (Audio toggles, promo code input)")
    lines.append("```\n")

    lines.append("---")
    lines.append("## 4. Server-Authoritative Remote Contracts (`ReplicatedStorage`)\n")
    lines.append("| Remote Name | Type | Direction | Server Validation Rule |")
    lines.append("|---|---|---|---|")
    lines.append("| `RequestAction` | RemoteEvent | Client -> Server | Rate-limit debounce (0.1s); server increments stats |")
    lines.append("| `PurchaseItem` | RemoteFunction | Client -> Server | Server verifies balance, deducts currency, grants item |")
    lines.append("| `TriggerRebirth` | RemoteFunction | Client -> Server | Server verifies milestone threshold before reset |")
    lines.append("| `ClaimCode` | RemoteFunction | Client -> Server | Check expiration & one-time claim record |")

    lines.append("\n---")
    lines.append("## 5. Implementation Roadmap for Coding Agent\n")
    lines.append("Instruct your AI coding agent (e.g. Antigravity with `roblox-game` skill) to execute:")
    lines.append("1. **DataStore Setup:** Use `ProfileService` in `ServerScriptService.DataManager` with `:BindToClose()` auto-save.")
    lines.append("2. **Remote Registration:** Define all RemoteEvents in `ReplicatedStorage.Remotes`.")
    lines.append("3. **UI Construction:** Build the `StarterGui` elements matching the captured screenshots and color palette.")
    lines.append("4. **Client-Server Wiring:** Implement client UI controllers and server-authoritative handlers.")
    lines.append("5. **Playtest & Tuning:** Verify animations and balance curves in Studio Play Mode.")

    return "\n".join(lines)
